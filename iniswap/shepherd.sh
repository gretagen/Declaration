#!/bin/bash
# iniswap handler: shepherd
#
# Ownership split mirrors the runit port: this handler GENERATES the base
# /etc/shepherd.scm (boot service + drop-in loader), while the service
# definitions themselves are drop-in files under /etc/shepherd.d/*.scm
# written by nacelle's shepherd-services generator. The early-boot and
# shutdown-teardown scripts are shared byte-identical with the dinit port
# and ship from the shepherd-services repo's install.sh.

install_shepherd() {
    # /sbin/shepherd is the PID1 entry point (matching the init=/sbin/shepherd
    # iniswap writes into limine.conf); /usr/bin/herd is the control client
    # the universal shutdown/reboot wrapper dispatches through.
    if [ -x /sbin/shepherd ] && [ -x /usr/bin/herd ]; then
        echo "  shepherd is already installed."
        return
    fi

    echo "  Installing shepherd via zeta..."
    zeta -provide --pass shepherd
}

generate_shepherd_services() {
    mkdir -p /etc/shepherd.d /etc/shepherd/scripts
    chmod +x /etc/shepherd/scripts/*.sh 2>/dev/null || true

    # Base configuration. Generated on every swap so nacelle owns it (same
    # split as runit, where /etc/runit/{1,2,3} are generated and /etc/service
    # ships from the rootfs). Keep byte-identical with
    # shepherd-services/shepherd/shepherd.scm.
    cat > /etc/shepherd.scm << 'SCM'
;; /etc/shepherd.scm — Haliade base shepherd configuration.
;;
;; Generated by the nacelle iniswap handler (nacelle/iniswap/shepherd.sh);
;; keep byte-identical with shepherd-services/shepherd/shepherd.scm.
;;
;; This file owns the 'boot' service — early boot via
;; /etc/shepherd/scripts/sysinit.sh and shutdown teardown via
;; /etc/shepherd/scripts/shutdown.sh (both shared with the dinit port) —
;; and loads service drop-ins from /etc/shepherd.d/*.scm in name order.
;; Each drop-in defines its service and registers it through
;; 'haliade-service!' below, so this file starts whatever happens to be
;; loaded without knowing the service list up front.

(use-modules (shepherd service)
             (ice-9 ftw)
             (srfi srfi-13))

;; Drop-ins register through this helper; the recorded order is the
;; 'start-in-the-background' list at the bottom. 'herd load root FILE'
;; re-evaluates a drop-in in this same module, so loading one again replaces
;; its registered definition rather than duplicating it.
(define haliade-service-names '())

(define (haliade-service! name svc)
  (set! haliade-service-names (cons name haliade-service-names))
  (register-services (list svc)))

;; Early boot. A regular service (NOT #:one-shot?) whose start is a plain
;; procedure: it stays "running" after sysinit.sh exits, which is what makes
;; its #:stop — the shutdown teardown — run when shepherd rolls the graph
;; down at halt/reboot. One-shot services return to "stopped" once their
;; start method finishes and would skip the teardown entirely.
(haliade-service!
 'boot
 (service
  '(boot)
  #:start (lambda ()
            (zero? (system* "/etc/shepherd/scripts/sysinit.sh")))
  #:stop (lambda (running)
           (system* "/etc/shepherd/scripts/shutdown.sh")
           #f)))

;; Load every drop-in, in name order. This is only the launch order:
;; shepherd still starts services by #:requirement.
(let ((dir "/etc/shepherd.d"))
  (when (file-exists? dir)
    (for-each
     (lambda (name)
       (when (string-suffix? ".scm" name)
         (load (string-append dir "/" name))))
     (sort (scandir dir) string<?))))

;; 'boot' is first in the reversed list; the daemons and gettys follow,
;; ordered among themselves by their #:requirement.
(start-in-the-background (reverse haliade-service-names))
SCM

    # Live-apply the base file only when shepherd really is PID 1: during
    # the swap window (declared, not yet booted) there is no shepherd to
    # talk to, and the file simply takes effect on the next boot.
    if [ "$(cat /proc/1/comm 2>/dev/null)" = "shepherd" ] && [ -x /usr/bin/herd ]; then
        herd load root /etc/shepherd.scm
    fi

    echo "  shepherd base config written (/etc/shepherd.scm)."
}
